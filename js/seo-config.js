/* نصوص السيو لصفحات الإعلانات — عناوين وأوصاف كل فئة، ومسمّيات الفئات.

   مصدر واحد للاتنين: المتصفّح (ads.html بيحمّله بوسم script) وسيرفر الرسم
   (netlify/functions/ssr-ads.js بيعمله require). قبل كانت هالنصوص جوّا ads.html
   بس؛ لمّا صار السيرفر يرسم الصفحة كان لازم يعرفها كمان — ونسختين بيتباعدوا
   مع أول تعديل، فطلعناها لهون. */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.SAAHA_SEO = factory();
}(typeof self !== 'undefined' ? self : this, function () {

  const CATEGORY_LABELS = {
    realestate: 'عقار', cars: 'سيارات', mobiles: 'موبايلات',
    furniture: 'أثاث', electronics: 'إلكترونيات', misc: 'غير مصنف',
  };

  const SEO_BY_CAT = {
    realestate: {
      noun: 'عقارات',
      title: 'عقارات للبيع والإيجار في سوريا من المالك | ساحة',
      desc: 'تصفح إعلانات عقارات للبيع والإيجار في سوريا: شقق، بيوت، أراضي ومحلات، معظمها من المالك مباشرة بدون وسيط. انشر إعلان عقارك مجاناً على ساحة.',
      h1: 'عروض عقارات بدون وسيط: بيع وشراء وتأجير في سوريا',
      h1City: city => `عروض عقارات بدون وسيط في ${city}: بيع وشراء وتأجير`,
    },
    cars: {
      noun: 'سيارات',
      title: 'سيارات للبيع في سوريا | ساحة',
      desc: 'تصفح إعلانات سيارات للبيع في سوريا من أصحابها مباشرة. سيارات جديدة ومستعملة بكل الماركات والمحافظات، وانشر إعلان سيارتك مجاناً على ساحة.',
      h1: 'عروض سيارات: بيع وشراء جديد ومستعمل في سوريا',
      h1City: city => `عروض سيارات في ${city}: بيع وشراء جديد ومستعمل`,
    },
    mobiles: {
      noun: 'موبايلات',
      title: 'موبايلات للبيع في سوريا: سامسونج، هواوي، آيفون | ساحة',
      desc: 'تصفح إعلانات موبايلات مستعملة وجديدة للبيع في سوريا: سامسونج، هواوي، آيفون وكل الماركات، بأفضل الأسعار. انشر إعلان موبايلك مجاناً على ساحة.',
      h1: 'عروض موبايلات: سامسونج وهواوي وآيفون بيع وشراء جديد ومستعمل',
      h1City: city => `عروض موبايلات في ${city}: بيع وشراء جديد ومستعمل`,
    },
    furniture: {
      noun: 'أثاث',
      title: 'أثاث مستعمل وجديد للبيع في سوريا | ساحة',
      desc: 'تصفح إعلانات أثاث مستعمل وجديد للبيع في سوريا: غرف نوم، صالونات، مطابخ وأثاث منزلي ومكتبي من أصحابه مباشرة. انشر إعلانك مجاناً على ساحة.',
      h1: 'عروض أثاث: بيع وشراء جديد ومستعمل في سوريا',
      h1City: city => `عروض أثاث في ${city}: بيع وشراء جديد ومستعمل`,
    },
    electronics: {
      noun: 'إلكترونيات',
      title: 'إلكترونيات وكمبيوترات للبيع في سوريا | ساحة',
      desc: 'تصفح إعلانات إلكترونيات وأجهزة منزلية وكمبيوترات ولابتوبات للبيع في سوريا، جديد ومستعمل بأفضل الأسعار. انشر إعلانك مجاناً على ساحة.',
      h1: 'عروض إلكترونيات: أجهزة منزلية وكمبيوترات ولابتوبات بيع وشراء جديد ومستعمل',
      h1City: city => `عروض إلكترونيات في ${city}: كمبيوترات ولابتوبات وأجهزة منزلية بيع وشراء`,
    },
    misc: {
      noun: 'إعلانات متنوعة',
      title: 'إعلانات متنوعة للبيع في سوريا | ساحة',
      desc: 'تصفح إعلانات متنوعة للبيع في سوريا: ملابس، أدوات، وأغراض شخصية متفرقة. منصة إعلانات مبوبة مجانية، انشر إعلانك خلال دقائق.',
      h1: 'عروض متنوعة: بيع وشراء جديد ومستعمل في سوريا',
      h1City: city => `عروض متنوعة في ${city}: بيع وشراء جديد ومستعمل`,
    },
  };

  const DEFAULT_SEO = {
    title: 'ساحة | عروض سوريا عقارات سيارات خدمات',
    desc: 'ساحة: منصة الإعلانات المبوبة في سوريا. عقارات، سيارات، موبايلات، أثاث وإلكترونيات من أصحابها مباشرة. تصفح أو انشر إعلانك مجاناً.',
    h1: 'عروض إعلانات في سوريا: بيع وشراء جديد ومستعمل',
  };

  /* بيحسب عنوان/وصف/h1/canonical لأي تركيبة فلاتر — نفس القواعد اللي كانت
     بـads.html حرفياً، بس بمكان واحد. */
  function pageSeo({ cat, city, q }) {
    const base = 'https://saaha.net/ads.html';
    const enc = encodeURIComponent;
    const seo = cat && SEO_BY_CAT[cat];
    if (q) {
      return { title: `نتائج البحث عن "${q}" | ساحة`, desc: DEFAULT_SEO.desc,
        h1: `نتائج البحث عن "${q}"`, canonical: cat ? `${base}?cat=${enc(cat)}` : base, noindex: true };
    }
    if (seo && city) {
      return { title: `${seo.noun} للبيع في ${city} | ساحة`,
        desc: `تصفح أحدث إعلانات ${seo.noun} للبيع في ${city}، سوريا. ${seo.desc}`,
        h1: seo.h1City(city), canonical: `${base}?cat=${enc(cat)}&city=${enc(city)}` };
    }
    if (seo) {
      return { title: seo.title, desc: seo.desc, h1: seo.h1, canonical: `${base}?cat=${enc(cat)}` };
    }
    if (city) {
      return { title: `أحدث الإعلانات المبوبة في ${city} | ساحة`,
        desc: `تصفح أحدث الإعلانات المبوبة في ${city}: عقارات، سيارات وإعلانات متنوعة. انشر إعلانك مجاناً على ساحة.`,
        h1: `عروض إعلانات في ${city}: بيع وشراء جديد ومستعمل`, canonical: `${base}?city=${enc(city)}` };
    }
    return { title: DEFAULT_SEO.title, desc: DEFAULT_SEO.desc, h1: DEFAULT_SEO.h1, canonical: base };
  }

  return { CATEGORY_LABELS, SEO_BY_CAT, DEFAULT_SEO, pageSeo };
}));
